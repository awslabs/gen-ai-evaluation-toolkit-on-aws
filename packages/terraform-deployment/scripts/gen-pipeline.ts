/**
 * gen-pipeline.ts
 *
 * Regenerates `.gitlab/generated/docker-plugin-matrix.yml` from
 * `packages/terraform-deployment/plugins.yaml` so that `docker:plugin`
 * in `.gitlab/pipeline.yml` is driven by the same source of truth as
 * the TF bootstrap (`aws_ecr_repository for_each`) and the deployment
 * package's `main.tf` (`plugin_ecr_lookup`).
 *
 * Invocation: `mise run gen-pipeline` (see root `mise.toml`).
 *
 * Design notes:
 *  - No npm deps: the monorepo doesn't declare `js-yaml` as a direct
 *    dependency, so we use a minimal line-oriented YAML parser scoped
 *    to the fixed `plugins.yaml` shape (plugins: list-of-scalar-maps).
 *    Output is manually string-built for deterministic, review-friendly
 *    diffs and identical indentation to the hand-written matrix this
 *    generator replaces.
 *  - OUTPUT_NAME == deploy_key (preserving underscore convention for
 *    ecs/lambda variants). Matches the inline matrix byte-for-byte so
 *    the downstream artifact path `output/images/${OUTPUT_NAME}.tar`
 *    keeps resolving to the same tarballs.
 *  - Field order inside each matrix entry matches the current hand-
 *    written pipeline.yml: PACKAGE_NAME, [DOCKER_FILE], OUTPUT_NAME,
 *    ECR_REPO_NAME — so a `git diff` of the first regeneration is
 *    whitespace-only.
 *  - Sync-guard: the generated file is committed; `ci:verify-generated`
 *    in `.gitlab/pipeline.yml` re-runs this script in CI and fails on
 *    any non-zero diff (so nobody hand-edits one side).
 */

import * as fs from 'fs';
import * as path from 'path';

interface PluginEntry {
  name: string;
  package: string;
  dockerfile?: string;
  docker_context?: string;
  ecr_repo: string;
  deploy_key: string;
}

const WORKSPACE_ROOT = path.resolve(__dirname, '..', '..', '..');
const PLUGINS_YAML = path.join(WORKSPACE_ROOT, 'packages', 'terraform-deployment', 'plugins.yaml');
const OUTPUT_PATH = path.join(WORKSPACE_ROOT, '.gitlab', 'generated', 'docker-plugin-matrix.yml');

/**
 * Minimal parser scoped to the known plugins.yaml shape. We avoid taking
 * on a YAML dep for a one-screen fixture; the schema is documented inline
 * in plugins.yaml and any drift (nested structure, anchors, multiline
 * strings) would fail loud in the downstream TF `yamldecode()` too.
 */
function parsePluginsYaml(contents: string): PluginEntry[] {
  const lines = contents.split('\n');
  const plugins: PluginEntry[] = [];
  let inPluginsList = false;
  let current: Partial<PluginEntry> | null = null;

  for (const rawLine of lines) {
    // Strip end-of-line comments only when not inside a quoted string.
    // plugins.yaml has no quoted strings in values, so a simple `#`-split
    // is correct here.
    const line = rawLine.replace(/\s+#.*$/, '');
    if (!line.trim()) continue;
    if (line.trim().startsWith('#')) continue;

    if (line === 'plugins:' || line.startsWith('plugins:')) {
      inPluginsList = true;
      continue;
    }
    if (!inPluginsList) continue;

    // List item marker `  - name: ...` begins a new entry. Flush the
    // prior one and start fresh.
    const listItemMatch = line.match(/^\s*-\s+(\w+):\s*(.+)$/);
    if (listItemMatch) {
      if (current) plugins.push(current as PluginEntry);
      current = {};
      current[listItemMatch[1] as keyof PluginEntry] = listItemMatch[2].trim() as never;
      continue;
    }

    // Continuation lines `    key: value` inside the current entry.
    const kvMatch = line.match(/^\s+(\w+):\s*(.+)$/);
    if (kvMatch && current) {
      current[kvMatch[1] as keyof PluginEntry] = kvMatch[2].trim() as never;
      continue;
    }
  }
  if (current) plugins.push(current as PluginEntry);

  // Validate required fields — fail fast with a pointer back at plugins.yaml.
  for (const p of plugins) {
    if (!p.name || !p.package || !p.ecr_repo || !p.deploy_key) {
      throw new Error(
        `plugins.yaml entry missing required field (name/package/ecr_repo/deploy_key): ${JSON.stringify(p)}`,
      );
    }
  }
  return plugins;
}

/**
 * Emits the GitLab CI fragment. Field order + indentation are chosen to
 * match the hand-written matrix in .gitlab/pipeline.yml verbatim, so the
 * first regeneration produces a whitespace-only diff for reviewer peace
 * of mind.
 */
function renderMatrix(plugins: PluginEntry[]): string {
  const lines: string[] = [];
  lines.push(
    '# AUTO-GENERATED by `mise run gen-pipeline` — edit packages/terraform-deployment/plugins.yaml, not this file.',
  );
  lines.push('# Source: packages/terraform-deployment/plugins.yaml');
  lines.push('# Generator: packages/terraform-deployment/scripts/gen-pipeline.ts');
  lines.push('#');
  lines.push('# Single fan-out job for every plugin image. `docker:plugin` extends');
  lines.push('# `.docker_build_template` (defined in .gitlab/pipeline.yml). Downstream');
  lines.push('# `needs: docker:plugin` waits for every matrix expansion and inherits');
  lines.push('# their tar artifacts.');
  lines.push('docker:plugin:');
  lines.push('  extends: .docker_build_template');
  lines.push('  parallel:');
  lines.push('    matrix:');

  for (const p of plugins) {
    lines.push(`      - PACKAGE_NAME: ${p.package}`);
    if (p.dockerfile && p.dockerfile !== 'Dockerfile') {
      lines.push(`        DOCKER_FILE: ${p.dockerfile}`);
    }
    if (p.docker_context) {
      lines.push(`        DOCKER_CONTEXT: ${p.docker_context}`);
    }
    // OUTPUT_NAME == deploy_key preserves the underscore convention that
    // the existing hand-written matrix uses (e.g. plugin-eval-ragas_ecs).
    // Downstream kaniko writes `output/images/${OUTPUT_NAME}.tar`; CDK's
    // deploy flow consumes these exact filenames.
    lines.push(`        OUTPUT_NAME: ${p.deploy_key}`);
    lines.push(`        ECR_REPO_NAME: ${p.ecr_repo}`);
  }

  // Trailing newline — standard POSIX text file terminator, keeps diffs clean.
  lines.push('');
  return lines.join('\n');
}

function main(): void {
  if (!fs.existsSync(PLUGINS_YAML)) {
    console.error(`ERROR: source not found: ${PLUGINS_YAML}`);
    process.exit(1);
  }
  const plugins = parsePluginsYaml(fs.readFileSync(PLUGINS_YAML, 'utf8'));
  if (plugins.length === 0) {
    console.error('ERROR: no plugin entries parsed from plugins.yaml');
    process.exit(1);
  }

  const rendered = renderMatrix(plugins);
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, rendered, 'utf8');

  console.log(
    `Generated ${path.relative(WORKSPACE_ROOT, OUTPUT_PATH)} from ${path.relative(
      WORKSPACE_ROOT,
      PLUGINS_YAML,
    )} (${plugins.length} plugins).`,
  );
}

main();
