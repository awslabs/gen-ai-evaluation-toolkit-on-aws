#!/usr/bin/env bash
# gen-backend-hcl.sh
#
# Auto-generates packages/terraform-deployment/backend.hcl from the caller's
# AWS profile. Terraform's backend config cannot reference variables or data
# sources (language limitation), so we template it here before
# `terraform init`.
#
# Called by the `plan` + `apply` NX targets so local dev needs only
# AWS_PROFILE + AWS_DEFAULT_REGION — no hand-edits to backend.hcl.
#
# Beta CI path: pipeline.yml runs the same script. Behaviour is identical.
# Customer deploys: customers either use this script (pointed at their own
# AWS profile + bucket naming) or hand-write their own backend.hcl in
# packages/terraform/ if running the customer module standalone.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" 2>/dev/null && pwd)"
if [ -z "${SCRIPT_DIR:-}" ]; then
  echo "ERROR: gen-backend-hcl: failed to resolve script directory." >&2
  exit 1
fi
# shellcheck source=common.sh
. "${SCRIPT_DIR}/common.sh"

etk::require_region
etk::resolve_env
etk::resolve_account

# Bootstrap prefix — derived from project_name (matches bootstrap var.project_name).
# Override via TF_VAR_project_name for multi-stack scenarios.
BOOTSTRAP_PREFIX="genai-${TF_VAR_project_name:-etk}"

BACKEND_HCL="${SCRIPT_DIR}/../backend.hcl"

if ! cat > "${BACKEND_HCL}" <<EOF
# AUTO-GENERATED by packages/terraform-deployment/scripts/gen-backend-hcl.sh.
# Regenerates from AWS_PROFILE / AWS_DEFAULT_REGION on every 'nx run
# terraform-deployment:plan'. Edit the generator, not this file.
bucket         = "${BOOTSTRAP_PREFIX}-terraform-state-${ACCOUNT_ID}"
key            = "etk/${ENV_NAME}/terraform.tfstate"
region         = "${REGION}"
dynamodb_table = "${BOOTSTRAP_PREFIX}-terraform-locks"
EOF
then
  echo "ERROR: failed to write ${BACKEND_HCL} — check filesystem permissions." >&2
  exit 1
fi
if [ ! -s "${BACKEND_HCL}" ]; then
  echo "ERROR: ${BACKEND_HCL} is empty after heredoc write." >&2
  exit 1
fi

echo "Generated backend.hcl for account=${ACCOUNT_ID} region=${REGION} env=${ENV_NAME}."
